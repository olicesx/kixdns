/// Install KixDNS as a Windows service.
///
/// Registers the service with the SCM so that it can be started automatically
/// on boot or manually via `sc start` / Services.msc.
pub fn install_service(config: &PathBuf, listener_label: &str) -> anyhow::Result<()> {
    let manager = ServiceManager::local_computer(
        None::<&str>, // default database (active)
        ServiceManagerAccess::CONNECT | ServiceManagerAccess::CREATE_SERVICE,
    )
    .context("failed to open Service Control Manager (try running as Administrator)")?;

    let exe_path = std::env::current_exe().context("failed to get current executable path")?;

    // Build launch arguments: "service run --config <path> --listener-label <label>"
    let launch_arguments: Vec<OsString> = vec![
        OsString::from("service"),
        OsString::from("run"),
        OsString::from("--config"),
        OsString::from(config.as_os_str()),
        OsString::from("--listener-label"),
        OsString::from(listener_label),
    ];

    let service_info = ServiceInfo {
        name: OsString::from(SERVICE_NAME),
        display_name: OsString::from(SERVICE_DISPLAY_NAME),
        service_type: ServiceType::OWN_PROCESS,
        start_type: ServiceStartType::AutoStart,
        error_control: ServiceErrorControl::Normal,
        executable_path: exe_path.clone(),
        launch_arguments,
        dependencies: vec![
            ServiceDependency::Service(OsString::from("Tcpip")),
            ServiceDependency::Service(OsString::from("Dnscache")),
        ],
        account_name: None,     // LocalSystem
        account_password: None, // LocalSystem
    };

    let service = manager
        .create_service(
            &service_info,
            ServiceAccess::CHANGE_CONFIG | ServiceAccess::START | ServiceAccess::DELETE,
        )
        .context("failed to create service (try running as Administrator)")?;

    // Set friendly description
    service
        .set_description(SERVICE_DESCRIPTION)
        .context("failed to set service description")?;

    println!("✓ Service '{}' installed successfully.", SERVICE_NAME);
    println!("  Display name : {}", SERVICE_DISPLAY_NAME);
    println!("  Binary path  : {}", exe_path.display());
    println!("  Config       : {}", config.display());
    println!("  Status       : Use `sc start KixDNS` or Services.msc to start.");
    Ok(())
}

/// Uninstall KixDNS from the SCM database.
pub fn uninstall_service() -> anyhow::Result<()> {
    let manager = ServiceManager::local_computer(
        None::<&str>, // default database (active)
        ServiceManagerAccess::CONNECT,
    )
    .context("failed to open Service Control Manager (try running as Administrator)")?;

    let service = manager
        .open_service(
            SERVICE_NAME,
            ServiceAccess::DELETE | ServiceAccess::STOP | ServiceAccess::QUERY_STATUS,
        )
        .context("service 'KixDNS' not found or cannot be opened")?;

    // Try to stop the service if it's running
    let status = service
        .query_status()
        .context("failed to query service status")?;

    if status.current_state != ServiceState::Stopped {
        println!("→ Stopping service '{}'...", SERVICE_NAME);
        service.stop()?;
        // Wait briefly for the service to stop
        std::thread::sleep(Duration::from_secs(3));
    }

    // Mark for deletion
    service
        .delete()
        .context("failed to delete service (try running as Administrator)")?;

    println!("✓ Service '{}' uninstalled successfully.", SERVICE_NAME);
    Ok(())
}

/// Run the service dispatcher (blocks the main thread until the service stops).
///
/// Called from `main()` when the user executes `kixdns service run`.
pub fn run_service_dispatcher(config: PathBuf, listener_label: String) -> anyhow::Result<()> {
    SERVICE_CONFIG
        .set((config, listener_label))
        .map_err(|_| anyhow::anyhow!("SERVICE_CONFIG already set (concurrent dispatch?)"))?;

    service_dispatcher::start(SERVICE_NAME, ffi_service_main)
        .context("service dispatcher failed to start")?;

    Ok(())
}
