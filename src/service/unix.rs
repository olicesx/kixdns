//!
//! Supports:
//! - systemd (most modern Linux distributions)
//! - OpenRC (Gentoo, Alpine Linux)
//! - Procd (OpenWrt)
//! - BSD rc.d (FreeBSD)
//!
//! Unix 服务管理：支持 systemd、OpenRC、Procd 和 BSD rc.d。

