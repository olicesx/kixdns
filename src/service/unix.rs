/// Run the DNS server with signal-based graceful shutdown.
///
/// Sets up handlers for SIGTERM, SIGINT, and SIGQUIT to trigger
/// a graceful shutdown of the server.
pub fn run_service(config: PathBuf, listener_label: String) -> anyhow::Result<()> {
    let rt = tokio::runtime::Builder::new_multi_thread()
        .enable_all()
        .build()
        .context("failed to build tokio runtime for service")?;

    rt.block_on(async move {
        let (shutdown_tx, shutdown_rx) = oneshot::channel::<()>();

        // Set up signal handlers inside the tokio runtime
        // 在 tokio 运行时内设置信号处理
        tokio::spawn(async move {
            wait_for_signal_async().await;
            let _ = shutdown_tx.send(());
        });

        crate::run_dns_server_with_shutdown(config, listener_label, shutdown_rx).await
    })?;

    info!("Service stopped gracefully");
    Ok(())
}

/// Wait for a termination signal using tokio's signal module.
/// Listens for SIGTERM, SIGINT, and SIGQUIT.
pub async fn wait_for_signal_async() {
    use tokio::signal::unix::{SignalKind, signal};

    let mut term = signal(SignalKind::terminate()).expect("failed to create SIGTERM listener");
    let mut int = signal(SignalKind::interrupt()).expect("failed to create SIGINT listener");
    let mut quit = signal(SignalKind::quit()).expect("failed to create SIGQUIT listener");

    tokio::select! {
        _ = term.recv() => info!("Received SIGTERM"),
        _ = int.recv() => info!("Received SIGINT"),
        _ = quit.recv() => info!("Received SIGQUIT"),
    }
}

