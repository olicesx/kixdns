/// Install KixDNS as a system service on Unix.
///
/// Auto-detects the init system and installs the appropriate service file.
pub fn install_service(config: &PathBuf, listener_label: &str) -> anyhow::Result<()> {
    let init = detect_init_system();
    let exe = std::env::current_exe().context("failed to get current executable path")?;

    println!("→ Detected init system: {}", init.description());

    match init {
        InitSystem::Systemd => install_systemd(&exe, config, listener_label),
        InitSystem::OpenRc => install_openrc(&exe, config, listener_label),
        InitSystem::Procd => install_procd(&exe, config, listener_label),
        InitSystem::BsdRc => install_bsd_rc(&exe, config, listener_label),
        InitSystem::Unknown | _ => {
            anyhow::bail!(
                "Could not auto-detect init system.\n\
                 ┌─ Please create a service script manually ──────────────────────┐\n\
                 │                                                                  │\n\
                 │  systemd:  Write a .service unit to /etc/systemd/system/         │\n\
                 │  OpenRC:   Write an init script to /etc/init.d/                  │\n\
                 │  Procd:    Write a procd script to /etc/init.d/                  │\n\
                 │  FreeBSD:  Write a rc.d script to /usr/local/etc/rc.d/           │\n\
                 │                                                                  │\n\
                 │  The binary is at: {}  │\n\
                 │  Run it with: {} run --config {}      │\n\
                 │                                                                  │\n\
                 └──────────────────────────────────────────────────────────────┘\n\
                 ",
                exe.display(),
                exe.display(),
                config.display(),
            )
        }
    }
}

fn install_systemd(exe: &Path, config: &Path, listener_label: &str) -> anyhow::Result<()> {
    let path = systemd_path();
    let content = systemd_unit(exe, config, listener_label);

    write_service_file(&path, &content, 0o644)?;

    // Reload systemd, enable and start
    run_command("systemctl", &["daemon-reload"])?;
    run_command("systemctl", &["enable", "kixdns"])?;
    run_command("systemctl", &["start", "kixdns"])?;

    println!("✓ KixDNS installed as a systemd service.");
    println!("  Unit file : {}", path.display());
    println!("  Status    : systemctl status kixdns");
    println!("  Logs      : journalctl -u kixdns -f");
    Ok(())
}

fn install_openrc(exe: &Path, config: &Path, listener_label: &str) -> anyhow::Result<()> {
    let path = openrc_path();
    let content = openrc_script(exe, config, listener_label);

    write_service_file(&path, &content, 0o755)?;

    run_command("rc-update", &["add", "kixdns", "default"])?;
    run_command("rc-service", &["kixdns", "start"])?;

    println!("✓ KixDNS installed as an OpenRC service.");
    println!("  Init script : {}", path.display());
    println!("  Status      : rc-service kixdns status");
    Ok(())
}

fn install_procd(exe: &Path, config: &Path, listener_label: &str) -> anyhow::Result<()> {
    let path = procd_path();
    let content = procd_script(exe, config, listener_label);

    write_service_file(&path, &content, 0o755)?;

    run_command("/etc/init.d/kixdns", &["enable"])?;
    run_command("/etc/init.d/kixdns", &["start"])?;

    println!("✓ KixDNS installed as a Procd service (OpenWrt).");
    println!("  Init script : {}", path.display());
    println!("  Status      : /etc/init.d/kixdns status");
    Ok(())
}

fn install_bsd_rc(exe: &Path, config: &Path, listener_label: &str) -> anyhow::Result<()> {
    let path = bsd_rc_path();
    let content = bsd_rc_script(exe, config, listener_label);

    write_service_file(&path, &content, 0o755)?;

    println!("✓ KixDNS installed as a FreeBSD rc.d service.");
    println!("  Script     : {}", path.display());
    println!("  Enable     : echo 'kixdns_enable=\"YES\"' >> /etc/rc.conf");
    println!("  Start      : service kixdns start");
    println!(
        "  Config     : Add 'kixdns_config=\"{}\"' to /etc/rc.conf for custom path",
        config.display()
    );
    Ok(())
}

