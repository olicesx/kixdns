/// Generate a systemd service unit.
///
/// Output: `/etc/systemd/system/kixdns.service`
fn systemd_unit(exe: &Path, config: &Path, listener_label: &str) -> String {
    format!(
        r#"# KixDNS systemd service unit
# Auto-generated by kixdns service install — do not edit manually.
#
# Install:  kixdns service install
# Uninstall: kixdns service uninstall
# Start:    systemctl start kixdns
# Enable:   systemctl enable kixdns

[Unit]
Description=KixDNS DNS Server
Documentation=https://github.com/kixdns/kixdns
After=network.target
Wants=nss-lookup.target

[Service]
Type=simple
ExecStart={exe} run \
    --config {config} \
    --listener-label {label}
Restart=on-failure
RestartSec=5
User=nobody
Group=nogroup
AmbientCapabilities=CAP_NET_BIND_SERVICE
NoNewPrivileges=true
LimitNOFILE=65536
PrivateTmp=true
ProtectSystem=full
ProtectHome=true

[Install]
WantedBy=multi-user.target
"#,
        exe = exe.display(),
        config = config.display(),
        label = listener_label,
    )
}

/// Generate an OpenRC init script.
///
/// Output: `/etc/init.d/kixdns`
fn openrc_script(exe: &Path, config: &Path, listener_label: &str) -> String {
    format!(
        r#"#!/sbin/openrc-run
# KixDNS OpenRC init script
# Auto-generated by kixdns service install — do not edit manually.
#
# Install:   kixdns service install
# Uninstall: kixdns service uninstall
# Start:     rc-service kixdns start
#           or: /etc/init.d/kixdns start

name="KixDNS DNS Server"
description="High-performance async DNS server with hot-reloadable pipeline configuration"
command="{exe}"
command_args="run --config {config} --listener-label {label}"
command_user="nobody:nogroup"
pidfile="/run/${{RC_SVCNAME}}.pid"
command_background=false

depend() {{
    need net
    use dns logger
}}
"#,
        exe = exe.display(),
        config = config.display(),
        label = listener_label,
    )
}

/// Generate a Procd init script (OpenWrt).
///
/// Output: `/etc/init.d/kixdns`
fn procd_script(exe: &Path, config: &Path, listener_label: &str) -> String {
    format!(
        r#"#!/bin/sh /etc/rc.common
# KixDNS Procd init script (OpenWrt)
# Auto-generated by kixdns service install — do not edit manually.
#
# Install:   kixdns service install
# Uninstall: kixdns service uninstall
# Start:     /etc/init.d/kixdns start
# Enable:    /etc/init.d/kixdns enable

USE_PROCD=1

start_service() {{
    procd_open_instance
    procd_set_param command "{exe}"
    procd_append_param command run --config {config} --listener-label {label}
    procd_set_param user nobody
    procd_set_param respawn 3600 5 0
    procd_set_param stdout 1
    procd_set_param stderr 1
    procd_close_instance
}}

stop_service() {{
    # The service will be stopped automatically by procd
    :
}}

service_triggers() {{
    procd_add_reload_trigger "kixdns"
}}
"#,
        exe = exe.display(),
        config = config.display(),
        label = listener_label,
    )
}

/// Generate a FreeBSD rc.d script.
///
/// Output: `/usr/local/etc/rc.d/kixdns`
fn bsd_rc_script(exe: &Path, config: &Path, listener_label: &str) -> String {
    format!(
        r#"#!/bin/sh
#
# PROVIDE: kixdns
# REQUIRE: NETWORKING SERVERS
# KEYWORD: shutdown
#
# Auto-generated by kixdns service install — do not edit manually.
#
# Install:   kixdns service install
# Uninstall: kixdns service uninstall
# Start:     service kixdns start
# Enable:    echo 'kixdns_enable="YES"' >> /etc/rc.conf

. /etc/rc.subr

name="kixdns"
rcvar="kixdns_enable"

load_rc_config $name

: ${{kixdns_enable:="NO"}}
: ${{kixdns_config:="{config}"}}
: ${{kixdns_listener_label:="{label}"}}
: ${{kixdns_user:="nobody"}}

command="{exe}"
command_args="run --config ${{kixdns_config}} --listener-label ${{kixdns_listener_label}}"
command_user="${{kixdns_user}}"
pidfile="/var/run/kixdns.pid"

run_rc_command "$1"
"#,
        exe = exe.display(),
        config = config.display(),
        label = listener_label,
    )
}

// ============================================================================
// Service file installation paths
// ============================================================================

fn systemd_path() -> PathBuf {
    PathBuf::from("/etc/systemd/system/kixdns.service")
}

fn openrc_path() -> PathBuf {
    PathBuf::from("/etc/init.d/kixdns")
}

fn procd_path() -> PathBuf {
    PathBuf::from("/etc/init.d/kixdns")
}

fn bsd_rc_path() -> PathBuf {
    PathBuf::from("/usr/local/etc/rc.d/kixdns")
}

