/// Uninstall KixDNS system service on Unix.
pub fn uninstall_service() -> anyhow::Result<()> {
    let init = detect_init_system();

    println!("→ Detected init system: {}", init.description());

    match init {
        InitSystem::Systemd => uninstall_systemd(),
        InitSystem::OpenRc => uninstall_openrc(),
        InitSystem::Procd => uninstall_procd(),
        InitSystem::BsdRc => uninstall_bsd_rc(),
        InitSystem::Unknown | _ => {
            anyhow::bail!(
                "Could not auto-detect init system.\n\
                 Please manually remove the service file you created earlier."
            );
        }
    }
}

fn uninstall_systemd() -> anyhow::Result<()> {
    let path = systemd_path();

    // Stop and disable
    let _ = run_command("systemctl", &["stop", "kixdns"]);
    let _ = run_command("systemctl", &["disable", "kixdns"]);

    // Remove unit file
    if path.exists() {
        std::fs::remove_file(&path).context("failed to remove systemd unit file")?;
    }
    let _ = run_command("systemctl", &["daemon-reload"]);

    println!("✓ KixDNS systemd service uninstalled.");
    Ok(())
}

fn uninstall_openrc() -> anyhow::Result<()> {
    let path = openrc_path();

    let _ = run_command("rc-service", &["kixdns", "stop"]);
    let _ = run_command("rc-update", &["delete", "kixdns"]);

    if path.exists() {
        std::fs::remove_file(&path).context("failed to remove OpenRC init script")?;
    }

    println!("✓ KixDNS OpenRC service uninstalled.");
    Ok(())
}

fn uninstall_procd() -> anyhow::Result<()> {
    let path = procd_path();

    if path.exists() {
        let _ = run_command("/etc/init.d/kixdns", &["stop"]);
        let _ = run_command("/etc/init.d/kixdns", &["disable"]);
        std::fs::remove_file(&path).context("failed to remove Procd init script")?;
    }

    println!("✓ KixDNS Procd service uninstalled.");
    Ok(())
}

fn uninstall_bsd_rc() -> anyhow::Result<()> {
    let path = bsd_rc_path();

    let _ = run_command("service", &["kixdns", "stop"]);

    if path.exists() {
        std::fs::remove_file(&path).context("failed to remove BSD rc.d script")?;
    }

    println!("✓ KixDNS BSD rc.d service uninstalled.");
    println!("  Note: You may want to remove 'kixdns_enable=\"YES\"' from /etc/rc.conf manually.");
    Ok(())
}

