/// Write a service file to disk, creating parent directories if needed.
fn write_service_file(path: &Path, content: &str, mode: u32) -> anyhow::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("failed to create directory: {}", parent.display()))?;
    }

    let mut file = std::fs::File::create(path)
        .with_context(|| format!("failed to create service file: {}", path.display()))?;

    file.write_all(content.as_bytes())
        .with_context(|| format!("failed to write service file: {}", path.display()))?;

    // Set file permissions
    use std::os::unix::fs::PermissionsExt;
    file.set_permissions(std::fs::Permissions::from_mode(mode))
        .with_context(|| format!("failed to set permissions on: {}", path.display()))?;

    Ok(())
}

/// Run a shell command and return its exit status.
fn run_command(program: &str, args: &[&str]) -> anyhow::Result<()> {
    let output = std::process::Command::new(program)
        .args(args)
        .output()
        .with_context(|| format!("failed to execute: {} {}", program, args.join(" ")))?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        anyhow::bail!(
            "Command failed ({} {}): {}",
            program,
            args.join(" "),
            stderr.trim()
        );
    }

    Ok(())
}
